def test_radvd_conf_rendered():
    assert radvd(KeaConfig(dhcp6=True, radvd=True, subnets6=[a_subnet()])) == RADVD_HEADER   # RA off: just the header
    text = radvd(KeaConfig(dhcp6=True, radvd=True, subnets6=[ra_subnet()]))
    assert 'interface ens19\n{' in text and 'AdvDefaultLifetime 0;' in text and 'AdvManagedFlag on;' in text
    assert 'prefix fd00:1:2:100::/64' in text and 'AdvAutonomous off;' in text
    assert agent_mod.validate_radvd(text) == ['ens19']
    slaac = radvd(KeaConfig(dhcp6=True, radvd=True, subnets6=[ra_subnet(ra_slaac=True)]))
    assert 'AdvAutonomous on;' in slaac
    # no pools and no reserved address: options only, so M is off
    options_only = radvd(KeaConfig(dhcp6=True, radvd=True, subnets6=[Subnet6(8, LAB, 'ens19', ra=True)]))
    assert 'AdvManagedFlag off;' in options_only and 'AdvOtherConfigFlag on;' in options_only
    reserved = Subnet6(8, LAB, 'ens19', ra=True, reservations=[Reservation6(1, 8, duid='00:01:02', ip_address='fd00:1:2:100::5')])
    assert 'AdvManagedFlag on;' in radvd(KeaConfig(dhcp6=True, radvd=True, subnets6=[reserved]))

    # only a node with radvd gets the file
    assert 'radvd.conf' not in render(KeaConfig(dhcp6=True, subnets6=[ra_subnet()]))
    assert render(KeaConfig(dhcp6=True, radvd=True, subnets6=[ra_subnet()]))['radvd.conf'] == text


