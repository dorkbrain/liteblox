def test_radvd_goes_with_keas_files(ra_client, layout):
    client, cfg, unit, sockets = ra_client
    status = client.status()['ra']
    assert status['ready'] and status['interfaces'] == [] and not status['active'] and status['in_place']

    files = render(KeaConfig(dhcp6=True, radvd=True, subnets6=[ra_subnet()], interfaces6=['ens19']), layout)
    assert client.check_dhcp(files)['ok']
    result = client.commit_dhcp(client.stage_dhcp(files)['stage_id'])
    assert Path(cfg['radvd_live']).read_text() == files['radvd.conf'] and unit.active
    assert result['files']['radvd.conf'] == hashlib.sha256(files['radvd.conf'].encode()).hexdigest()
    assert client.status()['ra'] == {'ready': True, 'installed': True, 'active': True, 'interfaces': ['ens19'],
                                     'in_place': True}
    assert 'radvd.conf' in client.dhcp_files()

    # unchanged radvd.conf: not written again, so radvd isn't restarted
    started = unit.started
    client.commit_dhcp(client.stage_dhcp(dict(files, **{'kea-dhcp6.conf': files['kea-dhcp6.conf'].replace(
        '"INFO"', '"DEBUG"')}))['stage_id'])
    assert unit.started == started

    # a rollback of the RA change stops radvd again
    off = render(KeaConfig(dhcp6=True, radvd=True, subnets6=[a_subnet()], interfaces6=['ens19']), layout)
    client.commit_dhcp(client.stage_dhcp(off)['stage_id'])
    assert not unit.active and Path(cfg['radvd_live']).read_text() == RADVD_HEADER
    client.rollback_dhcp()
    assert unit.active and Path(cfg['radvd_conf']).read_text() == files['radvd.conf']


def test_radvd_that_does_not_take_it_rolls_back(ra_client, layout):
    client, cfg, unit, sockets = ra_client
    unit.broken = True          # radvd --configtest failed in the oneshot: the file never gets into place
    files = render(KeaConfig(dhcp6=True, radvd=True, subnets6=[ra_subnet()], interfaces6=['ens19']), layout)
    with pytest.raises(AgentError) as e:
        client.commit_dhcp(client.stage_dhcp(files)['stage_id'])
    assert 'radvd did not take the new config' in e.value.message and 'not put in place' in e.value.details['output']
    assert Path(cfg['radvd_conf']).read_text() == RADVD_HEADER
    unit.broken = False


