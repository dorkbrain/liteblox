    (lambda t: t.replace('AdvDefaultLifetime 0;', 'AdvDefaultLifetime 1800;'), 'AdvDefaultLifetime 1800'),
    (lambda t: t.replace('    AdvDefaultLifetime 0;\n', ''), 'needs AdvSendAdvert on, AdvDefaultLifetime 0'),
