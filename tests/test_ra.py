def _nodes(conn, radvd=(1, 1)):
    with conn:
        for i, name in ((1, 'ns1'), (2, 'ns2')):
            conn.execute("INSERT INTO nodes (id, name, host, host_key, host_key_fp, dhcp, dhcp6, radvd, dhcp_interfaces) "
                         "VALUES (?, ?, ?, '', '', 1, 1, ?, '[\"ens19\"]')", (i, name, f'192.0.2.{i}', radvd[i - 1]))


def test_ra_needs_a_64_and_radvd_on_every_serving_node(conn):
    _nodes(conn, radvd=(1, 0))
    assert 'a /64' in ra.check(conn, Subnet6(1, 'fd00:1:2::/56', 'ens19', ra=True))['ra']
    assert 'ns2 can\'t send router advertisements' in ra.check(conn, ra_subnet())['ra']
    assert ra.check(conn, Subnet6(1, LAB, 'ens19')) == {}
    with conn:
        conn.execute('UPDATE nodes SET radvd = 1 WHERE id = 2')
    assert ra.check(conn, ra_subnet()) == {}


def test_the_dev_guard_refuses_ra_on_the_lan(monkeypatch):
    monkeypatch.setenv(validate.DEV_NEVER_SERVE, '192.168.1.0/24, fd00:1:2:100::/64')
    files = render(KeaConfig(dhcp6=True, radvd=True, subnets6=[ra_subnet()], interfaces6=['ens19']))
    with pytest.raises(validate.Invalid, match='refusing'):
        validate.guard_rendered(files)
    # an interface that carries a never-serve address, of either family, is refused for Kea and radvd alike
    node = {'name': 'ns1'}
    lan6 = [{'name': 'ens18', 'addresses': ['fe80::1/64', 'fd00:1:2:100::1/64']}]
    assert 'never serves' in validate.check_interfaces(node, ['ens18'], lan6, [])['interfaces']
    lan4 = [{'name': 'ens18', 'addresses': ['192.168.1.213/24', 'fe80::1/64']}]
    assert 'never serves' in validate.check_interfaces(node, ['ens18'], lan4, [])['interfaces']
    lab = [{'name': 'ens19', 'addresses': ['192.168.0.213/24', 'fe80::2/64']}]
    assert validate.check_interfaces(node, ['ens19'], lab, []) == {}

    from liteblox.dhcp.apply import served_interfaces
    files = render(KeaConfig(dhcp6=True, radvd=True, subnets6=[ra_subnet()]))
    assert 'ens19' in served_interfaces(files)


def test_the_dev_backstop_turns_ra_off(conn, monkeypatch, settings):
    from liteblox.dhcp import apply, store
    _nodes(conn)
    old = (datetime.now(timezone.utc) - timedelta(minutes=30)).strftime('%Y-%m-%d %H:%M:%S')
    store.save_subnet6(conn, ra_subnet(ra_since=old))
    store.save_subnet6(conn, Subnet6(8, 'fd00:1:2:101::/64', 'ens19', ra=True, ra_since=ra.now()))
    assert ra.expired(conn) == []                   # no limit set: a real install never turns RA off by itself
    monkeypatch.setenv(ra.DEV_RA_MAX, '20')
    assert [s.prefix for s in ra.expired(conn)] == [LAB]
    started = []

    def fake_start(settings, ids, reason, username, change=None, undo=None, background=True, kind=None, **kw):
        started.append((reason, kind))
        change(conn)
        return 1
    monkeypatch.setattr(apply, 'start', fake_start)
    line = ra.backstop(settings, conn, background=False)
    assert 'turning them off' in line and started == [(f'router advertisements off for {LAB} ({ra.DEV_RA_MAX})',
                                                       'ra auto off')]
    s = store.get_subnet6(conn, 7)
    assert not s.ra and s.ra_since is None and store.get_subnet6(conn, 8).ra
    assert conn.execute("SELECT detail FROM audit WHERE action = 'dhcp6_ra_auto_off'").fetchone()[0].startswith(LAB)


def test_the_form_turns_ra_on_and_keeps_since(conn):
    from liteblox.dhcp.routes6 import parse_subnet6, subnet6_values
    s, errors = parse_subnet6({'prefix': LAB, 'ra': '1', 'ra_slaac': '1'}, 7)
    assert not errors and s.ra and s.ra_slaac
    s, _ = parse_subnet6({'prefix': LAB, 'ra': '', 'ra_slaac': '1'}, 7)
    assert not s.ra and not s.ra_slaac             # SLAAC only goes with RA on
    assert subnet6_values(ra_subnet(ra_slaac=True))['ra'] == '1'


