@pytest.mark.skipif(not shutil.which('named-checkconf'), reason='named-checkconf not installed')
def test_rendered_set_passes_named_checkconf(tmp_path):
    files = render(full_model(), Layout(directory=str(tmp_path)))
    for role, text in files.items():
        text = text.replace('/etc/bind/liteblox/', f'{tmp_path}/').replace(
            '/etc/bind/named.conf.root-hints', f'{tmp_path}/hints')
        (tmp_path / role).write_text(text)
    (tmp_path / 'hints').write_text('zone "." { type hint; file "/usr/share/dns/root.hints"; };\n')
    r = subprocess.run(['named-checkconf', str(tmp_path / 'named.conf')], capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


