def test_stats_channel_beside_the_nodes_own_statements():
    from liteblox.bindconf.render import HEADER, STATS_CHANNEL, own_top
    files = render(NodeConfig(top_extra='logging { category lame-servers { null; }; };'))
    body = files['top.conf'][len(HEADER.format(pre_dir='/etc/bind/pre-liteblox')):]
    assert [st.keyword for st in agent.parse_conf(body)] == ['statistics-channels', 'logging']
    agent.validate_top(files['top.conf'], agent_cfg())
    # read back (Keep, re-adopt): the channel is LiteBlox's, not the node's own setting
    assert own_top(body) == 'logging { category lame-servers { null; }; };'
    # a node with its own channel keeps it, and gets no second one
    own = 'statistics-channels { inet 127.0.0.1 port 8080; };'
    files = render(NodeConfig(top_extra=own))
    assert STATS_CHANNEL not in files['top.conf'] and own in files['top.conf']


def test_render_is_ordered_and_hashable():
    a, b = full_model(), full_model()
    b.zones.reverse()
    assert render(a) == render(b)
    assert set_sha256(render(a)) == set_sha256(render(b))
    b.options.recursion = False
    assert set_sha256(render(a)) != set_sha256(render(b))


