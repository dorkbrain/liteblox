def test_render_full_model_passes_the_agents_allow_lists():
    files = render(full_model())
    assert sorted(files) == sorted(agent.CONFIG_ROLES)
    for role, text in files.items():
        agent.CONFIG_VALIDATORS[role](text, agent_cfg())
        assert text.startswith('// Generated by LiteBlox')
    assert agent.validate_named_conf(files['named.conf'], agent_cfg()) == [
        '/etc/bind/liteblox/acls.conf', '/etc/bind/liteblox/keys.conf', '/etc/bind/liteblox/options.conf',
        '/etc/bind/liteblox/top.conf', '/etc/bind/named.conf.root-hints', '/etc/bind/liteblox/zones.conf']
    zones = {z['name']: z for z in agent.validate_zones(files['zones.conf'], agent_cfg())}
    assert zones['example.com']['file'] == '/etc/bind/liteblox/db.example.com'
    assert zones['dyn.example.com'] == {'name': 'dyn.example.com', 'type': 'primary', 'dynamic': True,
                                        'file': '/var/lib/bind/liteblox/dyn/db.dyn.example.com', 'journal': None}
    assert zones['example.com']['journal'] == '/var/lib/bind/liteblox/jnl/db.example.com.jnl'
    assert zones['sec.example']['file'] == '/var/lib/bind/liteblox/sec/db.sec.example'
    assert zones['corp'] == {'name': 'corp', 'type': 'forward', 'file': None, 'dynamic': False, 'journal': None}
    assert 'validate-except { "corp"; };' in files['options.conf']
    assert '\t// extra statements\n\tminimal-responses yes;' in files['options.conf']


