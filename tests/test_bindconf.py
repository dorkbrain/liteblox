def full_model():
    return NodeConfig(
        options=NodeOptions(listen_on=['any'], listen_on_v6=['any'], allow_query=['lan'], recursion=True,
                            allow_recursion=['localnets', 'localhost'], forwarders=['1.1.1.1', '9.9.9.9'],
                            forward='first', dnssec_validation='auto', validate_except=['corp.'],
                            extra='minimal-responses yes;\nrate-limit {\n\tresponses-per-second 10;\n};'),
        acls=[Acl('lan', ['192.168.1.0/24', 'localhost'])],
        keys=[TsigKey('liteblox', 'hmac-sha256', 'c2VjcmV0c2VjcmV0c2VjcmV0'),
              TsigKey('dhcp', 'hmac-sha512', 'c2VjcmV0c2VjcmV0c2VjcmV0'),
              TsigKey('acme', 'hmac-sha1', 'c2VjcmV0c2VjcmV0c2VjcmV0')],
        zones=[ZoneDecl('example.com', notify='yes', allow_transfer=['key liteblox'], ixfr=True),
               ZoneDecl('dyn.example.com', dynamic=True, allow_transfer=['key liteblox'],
                        update_policy=['grant liteblox zonesub ANY', 'grant dhcp zonesub A AAAA DHCID',
                                       'grant acme name _acme-challenge.dyn.example.com. TXT',
                                       'grant acme subdomain h.dyn.example.com. ANY']),
               ZoneDecl('sec.example', kind='secondary', primaries=['192.0.2.1 key liteblox']),
               ZoneDecl('corp', kind='forward', forward_mode='only', forwarders=['10.0.0.1'])],
        top_extra='logging {\n\tchannel q { file "/var/log/named/q.log"; };\n\tcategory queries { q; };\n};',
        distro_includes=['/etc/bind/named.conf.root-hints'])


def agent_cfg(**over):
    return dict(agent.DEFAULT_CONFIG, **over)


def config_answer(printed, conf_files, declared_in):
    """An agent /config answer for a printed config, every zone declared in `declared_in`."""
    zones = agent.zones_from_conf(agent.parse_conf(printed))
    for z in zones:
        z['declared_in'] = declared_in
    return {'checkconf': printed, 'zones': zones, 'conf_files': conf_files, 'declared': {}}


