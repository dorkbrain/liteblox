def test_restricted_allow_query_still_admits_the_secondaries():
    row = {'name': 'a.lab', 'notify': 'no', 'also_notify': '', 'allow_transfer': '', 'allow_query': ''}
    p, s = _node(1, 'primary', '192.0.2.1'), _node(2, 'secondary', '192.0.2.2')
    assert zone_decl(row, p, p, [p, s]).allow_query == []                      # nothing restricted
    restricted = dict(p, options=NodeOptions(allow_query=['trusted']).to_json())
    assert zone_decl(row, restricted, restricted, [restricted, s]).allow_query == ['key liteblox-xfr', 'trusted']
    zone_level = dict(row, allow_query='lan')
    assert zone_decl(zone_level, p, p, [p, s]).allow_query == ['key liteblox-xfr', 'lan']
    assert zone_decl(zone_level, p, p, [p]).allow_query == ['lan']             # no secondaries: as written
    assert zone_decl(zone_level, s, p, [p, s]).allow_query == ['lan']          # the secondary's own copy
