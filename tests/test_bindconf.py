def _node(id, role, host):
    return {'id': id, 'role': role, 'host': host, 'dns_address': None, 'name': f'n{id}'}


def test_zone_decl_follows_the_topology():
    row = {'name': 'a.lab', 'notify': 'no', 'also_notify': '', 'allow_transfer': 'key ext', 'allow_query': 'lan'}
    p, s1, s2 = _node(1, 'primary', '192.0.2.1'), _node(2, 'secondary', '192.0.2.2'), _node(3, None, '192.0.2.3')
    assert zone_decl(row, p, None, [p]).ixfr is False                 # no primary picked: as before
    decl = zone_decl(row, p, p, [p, s1, s2])
    assert decl.also_notify == ['192.0.2.2'] and decl.notify == 'explicit' and decl.ixfr
    assert decl.allow_transfer == ['key liteblox-xfr', 'key ext']
    assert zone_decl(row, p, p, [p]).also_notify == []                # no secondaries: plain primary
    sec = zone_decl(row, s1, p, [p, s1])
    assert (sec.kind, sec.primaries, sec.notify, sec.allow_query) == (
        'secondary', ['192.0.2.1 key liteblox-xfr'], 'no', ['lan'])
    assert zone_decl(row, s2, p, [p, s2]).kind == 'primary'          # taken over later, not converted yet
    assert node_address(dict(p, host='ns1.example.lab')) is None
    assert node_address(dict(p, host='ns1.example.lab', dns_address='2001:db8::1')) == '2001:db8::1'
    for d in (decl, sec):
        agent.validate_zones(zone_stanza(d), agent_cfg())


def test_a_dynamic_zone_takes_updates_on_the_primary_only():
    row = {'name': 'd.lab', 'notify': '', 'also_notify': '', 'allow_transfer': '', 'allow_query': 'lan',
           'dynamic': 1, '_grants': ['grant dhcp zonesub A AAAA DHCID']}
    p, s1 = _node(1, 'primary', '192.0.2.1'), _node(2, 'secondary', '192.0.2.2')
    decl = zone_decl(row, p, p, [p, s1])
    assert decl.dynamic and decl.ixfr is False and decl.file_for() == '/var/lib/bind/liteblox/dyn/db.d.lab'
    assert decl.update_policy == ['grant liteblox zonesub ANY', 'grant dhcp zonesub A AAAA DHCID']
    assert decl.allow_transfer == ['key liteblox', 'key liteblox-xfr']
    assert decl.allow_query == ['key liteblox', 'key liteblox-xfr', 'lan']      # signed reads get through
    stanza = zone_stanza(decl)
    assert 'update-policy { grant liteblox zonesub ANY; grant dhcp zonesub A AAAA DHCID; };' in stanza
    assert 'ixfr-from-differences' not in stanza
    sec = zone_decl(row, s1, p, [p, s1])
    assert sec.kind == 'secondary' and not sec.dynamic and 'update-policy' not in zone_stanza(sec)
    for d in (decl, sec):
        agent.validate_zones(zone_stanza(d), agent_cfg())


