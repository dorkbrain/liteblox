def test_a_zone_shared_with_a_node_not_taken_over_stays_local(conn, settings, node, own_root, fake_layout):
    from liteblox.dns.repo import Repo, zone_file
    bind = own_root / 'etc/bind'
    text = (bind / 'db.example.com').read_text()
    Repo(settings.repo_dir).ensure().write(zone_file('example.com'), text, 'Import', 'admin')
    other = nodes.add_node(conn, 'old1', '192.0.2.99', 22, 8530, HOST_KEY, FP)
    with conn:
        zone_id = conn.execute("INSERT INTO zones (name, mode, repo_file) VALUES ('example.com', 'local', ?)",
                               (zone_file('example.com'),)).lastrowid
        for node_id in (node['id'], other):
            conn.execute('INSERT INTO zone_nodes (zone_id, node_id, node_file, deployed_sha256) VALUES (?, ?, ?, ?)',
                         (zone_id, node_id, str(bind / 'db.example.com'), 'old-hash'))
    takeover.takeover(conn, settings, node, 'admin', print, check_dns=no_dns_check, dns_serial=serials(7))
    zone = conn.execute('SELECT * FROM zones WHERE id = ?', (zone_id,)).fetchone()
    assert zone['mode'] == 'local' and zone['allow_transfer'] == 'key xfer'
    link = conn.execute('SELECT * FROM zone_nodes WHERE zone_id = ? AND node_id = ?', (zone_id, node['id'])).fetchone()
    assert link['node_file'].endswith('/liteblox/db.example.com') and link['deployed_sha256'] == 'old-hash'
    assert [z['name'] for z in declare.managed_zones_for(conn, node['id'])] == ['example.com']
    with pytest.raises(declare.DeclareError, match='old1 is not taken over yet'):    # until old1 is too
        declare.update_settings(settings, 'example.com', 'yes', '', '', 'admin', print)


