DHCP_ZONE = '@ IN SOA ns1.dhcp.example. root.dhcp.example. 9 1 1 1 1\n@ IN NS ns1\nns1 IN A 192.0.2.53\npc1 IN A 192.0.2.80\n'


@pytest.fixture
def dynamic_root(own_root):
    """own_root plus a dynamic zone with a journal, its updates allowed to the node's own key."""
    var = own_root / 'var/lib/bind'
    var.mkdir(parents=True, exist_ok=True)
    (var / 'db.dhcp.example').write_text(DHCP_ZONE)
    (var / 'db.dhcp.example.jnl').write_bytes(b'named journal')
    with open(own_root / 'etc/bind/named.conf.local', 'a') as f:
        f.write(f'zone "dhcp.example" {{\n  type master;\n  file "{var}/db.dhcp.example";\n'
                f'  update-policy {{ grant xfer zonesub A DHCID; }};\n}};\n')
    return own_root


def test_takeover_of_a_dynamic_zone(conn, settings, node, dynamic_root, fake_layout):
    pv = takeover.preview(conn, settings, node)
    assert pv.ready, (pv.blockers, pv.diff)
    assert 'sync dhcp.example' in rndc_log(dynamic_root)
    assert 'dynamic: grant xfer zonesub A DHCID' in '\n'.join(takeover.summary_lines(pv))
    log, say = lines()
    takeover.takeover(conn, settings, node, 'admin', say, check_dns=no_dns_check,
                      dns_serial=lambda host, zone: 9 if zone == 'dhcp.example' else 7)
    calls = rndc_log(dynamic_root)
    assert calls.index('freeze dhcp.example') < calls.index('reconfig') < calls.index('thaw dhcp.example')
    assert (dynamic_root / 'var/lib/bind/liteblox/dyn/db.dhcp.example').read_text() == DHCP_ZONE
    zones_conf = (dynamic_root / 'etc/bind/liteblox/zones.conf').read_text()
    assert 'update-policy { grant xfer zonesub A DHCID; };' in zones_conf
    zone = conn.execute("SELECT * FROM zones WHERE name = 'dhcp.example'").fetchone()
    assert zone['dynamic'] == 1 and zone['mode'] == 'managed'
    grants = conn.execute('SELECT k.name, g.scope, g.name, g.types FROM key_grants g JOIN tsig_keys k ON k.id = g.key_id '
                          'WHERE g.zone_id = ?', (zone['id'],)).fetchall()
    assert [tuple(g) for g in grants] == [('xfer', 'zonesub', '', 'A DHCID')]
    assert any('updates held (rndc freeze) at serial 9' in line for line in log)


def test_a_refused_dynamic_takeover_lets_the_zone_take_updates_again(conn, settings, node, dynamic_root, fake_layout,
                                                                    monkeypatch):
    from liteblox.nodes.client import AgentClient, AgentError

    def refuse(self, *a, **kw):
        raise AgentError(422, 'named-checkconf rejected the config')
    monkeypatch.setattr(AgentClient, 'stage_config', refuse)
    with pytest.raises(takeover.TakeoverError, match='refused the generated config'):
        takeover.takeover(conn, settings, node, 'admin', print, check_dns=no_dns_check, dns_serial=serials(7))
    assert rndc_log(dynamic_root)[-1] == 'thaw dhcp.example'
    assert nodes.get_node(conn, node['id'])['managed'] == 0
