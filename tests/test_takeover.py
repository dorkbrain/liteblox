@pytest.fixture
def own_root(fake_root):  # noqa: F811
    """The fake node with options, an ACL, a TSIG key and a zone of its own (written the way people do)."""
    bind = fake_root / 'etc/bind'
    (bind / 'named.conf').write_text(f'include "{bind}/named.conf.options";\n'
                                     f'include "{bind}/named.conf.local";\n'
                                     f'include "{bind}/named.conf.default-zones";\n')
    (bind / 'named.conf.options').write_text(
        f'acl trusted {{ localhost; 192.0.2.0/24; }};\n'
        f'options {{\n  directory "{fake_root}/var/cache/bind";\n  recursion yes;\n'
        f'  allow-recursion {{ trusted; }};\n  listen-on port 53 {{ any; }};\n  minimal-responses yes;\n}};\n'
        f'statistics-channels {{ inet 127.0.0.1 port 8053; }};\n')
    (bind / 'named.conf.local').write_text(
        f'key "xfer" {{ algorithm hmac-sha256; secret "c2VjcmV0c2VjcmV0"; }};\n'
        f'zone "example.com" {{\n  type master;\n  file "{bind}/db.example.com";\n'
        f'  allow-transfer {{ key xfer; }};\n}};\n')
    return fake_root


def serials(*values):
    """A dns_serial stand-in answering with these serials in turn (the last one repeats)."""
    values = list(values)
    return lambda host, zone: values.pop(0) if len(values) > 1 else values[0]


def test_preview_of_an_existing_config(conn, settings, node, own_root, fake_layout):
    pv = takeover.preview(conn, settings, node)
    assert pv.blockers == [] and pv.diff == '' and pv.ready
    plan = pv.plan
    assert plan.config.options.recursion is True and plan.config.options.allow_recursion == ['trusted']
    assert 'listen-on port 53' in plan.config.options.extra and 'minimal-responses yes;' in plan.config.options.extra
    assert [(a.name, a.items) for a in plan.acls] == [('trusted', ['localhost', '192.0.2.0/24'])]
    assert [(k.name, k.secret) for k in plan.keys] == [('xfer', 'c2VjcmV0c2VjcmV0')]   # from -p, not -px
    assert plan.config.top_extra.startswith('statistics-channels')
    (zone,) = plan.zones
    assert zone.relocated and zone.new_file == f"{fake_layout.config_dir}/db.example.com"
    assert zone.settings['allow_transfer'] == 'key xfer' and zone.settings['notify'] == ''
    bind = own_root / 'etc/bind'
    assert plan.retire == [str(bind / 'named.conf.options'), str(bind / 'named.conf.local')]
    assert str(bind / 'db.example.com') in plan.left_in_place
    assert 'c2VjcmV0c2VjcmV0' not in '\n'.join(takeover.summary_lines(pv))


def test_takeover_of_an_existing_config(conn, settings, node, own_root, fake_layout):
    bind = own_root / 'etc/bind'
    original = (bind / 'db.example.com').read_bytes()
    takeover.takeover(conn, settings, node, 'admin', print, check_dns=no_dns_check, dns_serial=serials(7))
    assert (bind / 'liteblox/db.example.com').read_bytes() == original
    assert (bind / 'db.example.com').exists()                   # left in place, unused
    assert not (bind / 'named.conf.local').exists()
    zones_conf = (bind / 'liteblox/zones.conf').read_text()
    assert 'allow-transfer { key xfer; };' in zones_conf and 'notify' not in zones_conf
    assert 'secret "c2VjcmV0c2VjcmV0"' in (bind / 'liteblox/keys.conf').read_text()

    zone = conn.execute("SELECT * FROM zones WHERE name = 'example.com'").fetchone()
    assert zone['mode'] == 'managed' and zone['allow_transfer'] == 'key xfer' and zone['notify'] == ''
    link = conn.execute('SELECT * FROM zone_nodes WHERE zone_id = ?', (zone['id'],)).fetchone()
    assert link['node_file'] == f'{fake_layout.config_dir}/db.example.com'
    assert conn.execute("SELECT items FROM acls WHERE name = 'trusted'").fetchone()[0] == '["localhost", "192.0.2.0/24"]'
    assert conn.execute("SELECT purpose FROM tsig_keys WHERE name = 'xfer'").fetchone()[0] == 'imported'

    # the zone now publishes to its new file, and zone changes keep the imported settings
    with nodes.agent_client(settings, node) as c:
        z = c.get_zone('example.com')
        assert z['file'] == link['node_file']
        c.commit_zone('example.com', c.stage_zone('example.com', z['content'] + '; edited\n', z['sha256'])['stage_id'])
    assert (bind / 'liteblox/db.example.com').read_text().endswith('; edited\n')
    declare.update_settings(settings, 'example.com', 'explicit', '192.0.2.9', 'key xfer', 'admin', print)
    zones_conf = (bind / 'liteblox/zones.conf').read_text()
    assert 'notify explicit;' in zones_conf and 'also-notify { 192.0.2.9; };' in zones_conf
    assert 'minimal-responses yes;' in (bind / 'liteblox/options.conf').read_text()


