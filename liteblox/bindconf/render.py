"""Render a node's whole generated BIND config from the model.

render() returns {role: text} for every file in model.ROLES; the agent checks
each against its own allow-list before anything is written.
"""

import hashlib
import json

from .model import DEBIAN, ROLES

HEADER = ('// Generated by LiteBlox. Do not edit: LiteBlox rewrites this file on every change\n'
          '// and keeps the node\'s original config in {pre_dir}/.\n')
# the agent reads BIND's query counters here (agent DEFAULT_CONFIG bind_stats_url)
STATS_CHANNEL = 'statistics-channels {\n\tinet 127.0.0.1 port 8053 allow { 127.0.0.1; };\n};'


def _quote(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def _list(items):
    return '{ ' + ' '.join(f'{i};' for i in items) + ' }' if items else '{ }'


def _indent(text, depth=1):
    pad = '\t' * depth
    return [pad + line if line.strip() else '' for line in text.strip('\n').splitlines()]


def zone_stanza(zone, layout=DEBIAN):
    lines = [f'zone {_quote(zone.name)} {{']
    if zone.kind == 'forward':
        lines.append('\ttype forward;')
        if zone.forward_mode:
            lines.append(f'\tforward {zone.forward_mode};')
        lines.append(f'\tforwarders {_list(zone.forwarders)};')
    else:
        lines.append(f'\ttype {zone.kind};')
        if zone.kind == 'secondary':
            lines.append(f'\tprimaries {_list(zone.primaries)};')
            lines.append('\tmasterfile-format text;')
        lines.append(f'\tfile {_quote(zone.file_for(layout))};')
        if zone.notify:
            lines.append(f'\tnotify {zone.notify};')
        for option, items in (('also-notify', zone.also_notify), ('allow-transfer', zone.allow_transfer),
                              ('allow-query', zone.allow_query)):
            if items:
                lines.append(f'\t{option} {_list(items)};')
        if zone.journal_for(layout):
            lines.append('\tixfr-from-differences yes;')
            lines.append(f'\tjournal {_quote(zone.journal_for(layout))};')
        if zone.kind == 'primary' and zone.dynamic:
            lines.append(f'\tupdate-policy {_list(zone.update_policy)};' if zone.update_policy
                         else '\tupdate-policy local;')
    lines.append('};')
    return '\n'.join(lines)


def options_text(options, layout=DEBIAN):
    o = options
    lines = [f'\tdirectory {_quote(layout.directory)};']
    for option, items in (('listen-on', o.listen_on), ('listen-on-v6', o.listen_on_v6),
                          ('allow-query', o.allow_query)):
        if items is not None:
            lines.append(f'\t{option} {_list(items)};')
    if o.recursion is not None:
        lines.append(f"\trecursion {'yes' if o.recursion else 'no'};")
    if o.allow_recursion is not None:
        lines.append(f'\tallow-recursion {_list(o.allow_recursion)};')
    if o.forwarders is not None:
        lines.append(f'\tforwarders {_list(o.forwarders)};')
    if o.forward:
        lines.append(f'\tforward {o.forward};')
    if o.dnssec_validation:
        lines.append(f'\tdnssec-validation {o.dnssec_validation};')
    if o.validate_except:
        lines.append(f'\tvalidate-except {_list(_quote(d.rstrip(".")) for d in o.validate_except)};')
    if o.extra.strip():
        lines += ['', '\t// extra statements'] + _indent(o.extra)
    return 'options {\n' + '\n'.join(lines) + '\n};\n'


def top_text(top_extra):
    """top.conf: the node's own top-level statements, and BIND's statistics channel for the Dashboard
    (localhost only; the agent reads it). A node that declares its own channel keeps it instead."""
    extra = top_extra.strip()
    own = 'statistics-channels' in extra
    return ('' if own else f'\n{STATS_CHANNEL}\n') + (f'\n{extra}\n' if extra else '')


def own_top(text):
    """A node's top.conf body (header already removed) without LiteBlox's statistics channel:
    the node's own top-level statements, read back by Keep and re-adopt."""
    return text.replace(STATS_CHANNEL, '', 1).strip()


def render(config, layout=DEBIAN):
    header = HEADER.format(pre_dir=layout.pre_dir)
    includes = ([layout.path(r) for r in ('acls.conf', 'keys.conf', 'options.conf', 'top.conf')]
                + list(config.distro_includes) + [layout.path('zones.conf')])
    files = {
        'named.conf': header + ''.join(f'include {_quote(p)};\n' for p in includes),
        'acls.conf': header + ''.join(f'\nacl {_quote(a.name)} {_list(a.items)};\n' for a in config.acls),
        'keys.conf': header + ''.join(
            f'\nkey {_quote(k.name)} {{\n\talgorithm {k.algorithm};\n\tsecret {_quote(k.secret)};\n}};\n'
            for k in config.keys),
        'options.conf': header + '\n' + options_text(config.options, layout),
        'top.conf': header + top_text(config.top_extra),
        'zones.conf': header + ''.join(f'\n{zone_stanza(z, layout)}\n'
                                       for z in sorted(config.zones, key=lambda z: z.name)),
    }
    assert tuple(sorted(files)) == tuple(sorted(ROLES))
    return files


def set_sha256(files):
    """One hash over a rendered set, stored as nodes.config_sha256."""
    return hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()


def file_hashes(files):
    """{role: sha256} of a rendered set, as the agent's /status reports the files on disk."""
    return {role: hashlib.sha256(text.encode('utf-8')).hexdigest() for role, text in files.items()}


def record_commit(conn, node_id, files):
    """Remember what was just committed to a node, for config drift checks."""
    with conn:
        conn.execute('UPDATE nodes SET config_sha256 = ?, config_files = ?, drift = NULL, second_primary = NULL '
                     'WHERE id = ?', (set_sha256(files), json.dumps(file_hashes(files)), node_id))
