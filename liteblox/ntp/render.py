"""chrony.conf for one node: the lines Debian ships, the sources, and what it serves."""

import hashlib
import re

HEADER = ('# Generated by LiteBlox. Do not edit: LiteBlox rewrites this file on every change\n'
          '# and keeps the node\'s original config in /etc/chrony/pre-liteblox/.\n')
# Debian 13's chrony.conf, without its default pool and the sourcedir/confdir lines (so nothing but
# LiteBlox's sources, and no servers learned by DHCP, gets in)
FIXED = ('keyfile /etc/chrony/chrony.keys\n'
         'driftfile /var/lib/chrony/chrony.drift\n'
         'ntsdumpdir /var/lib/chrony\n'
         'logdir /var/log/chrony\n'
         'maxupdateskew 100.0\n'
         'rtcsync\n'
         'makestep 1 3\n')
LEAP_LIST = 'leapseclist /usr/share/zoneinfo/leap-seconds.list\n'
LEAP_TZ = 'leapsectz right/UTC\n'      # chrony before 4.6 (Ubuntu 24.04's 4.5), as Ubuntu's own config has it


def chrony_version(text):
    """'4.5' from `chronyd -v` (chronyd (chrony) version 4.5 (+CMDMON ...)), else None."""
    m = re.search(r'version (\d+\.\d+(?:\.\d+)?)', text or '')
    return m.group(1) if m else None


def leap_line(version):
    m = re.match(r'\s*(\d+)\.(\d+)', version or '')
    return LEAP_TZ if m and (int(m.group(1)), int(m.group(2))) < (4, 6) else LEAP_LIST


def chrony_conf(config):
    text = HEADER + '\n# where this node gets its time\n' + ''.join(s.line() + '\n' for s in config.sources)
    if config.serve and config.allow:
        text += '\n# who may ask this node for the time\n' + ''.join(f'allow {n}\n' for n in config.allow)
        if config.local:
            # keeps answering its clients when every upstream is gone; with a second server they agree (orphan)
            text += f'local stratum {config.local} orphan\n'
    return text + '\n' + FIXED + leap_line(config.chrony_version)


def render(config):
    return {'chrony.conf': chrony_conf(config)}


def file_hashes(files):
    return {role: hashlib.sha256(text.encode()).hexdigest() for role, text in files.items()}
